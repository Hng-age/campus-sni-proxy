def _normalize_suffix(suffix):
    s = (suffix or "").strip().lower()
    if s.startswith("*."):
        s = s[2:]
    elif s.startswith("."):
        s = s[1:]
    return s


def generate_pac_script(port=8888, blocked_suffixes=None, rewrites=None,
                        passthrough_suffixes=None):
    """Generate high-performance PAC JavaScript content."""
    if passthrough_suffixes is None:
        passthrough_suffixes = config.PASSTHROUGH_SUFFIXES
    suffixes = list(dict.fromkeys(
        [_normalize_suffix(s) for s in
         list(blocked_suffixes or config.BLOCKED_SUFFIXES)
         + list(passthrough_suffixes) if s]
    ))
    rewrites_map = rewrites if rewrites is not None else config.SNI_REWRITE

    suffixes_json = json.dumps(suffixes, ensure_ascii=False)
    rewrites_json = json.dumps(list(rewrites_map.keys()), ensure_ascii=False)

    return f"""// SNI Proxy Auto-Config Script (PAC)
// Generated by SNI Proxy Desktop v{config.VERSION}
// 模式：智能分流模式（仅被拦截域名走本地代理，其余全部 DIRECT 直连）

function FindProxyForURL(url, host) {{
    if (!host) return "DIRECT";
    host = host.toLowerCase();

    // 1. 本地回环、局域网及无点单名称直接放行
    if (isPlainHostName(host) ||
        host === "localhost" ||
        host === "127.0.0.1" ||
        shExpMatch(host, "*.local")) {{
        return "DIRECT";
    }}

    // 2. 检查特定重写映射列表
    var rewrites = {rewrites_json};
    for (var j = 0; j < rewrites.length; j++) {{
        if (host === rewrites[j]) {{
            return "PROXY 127.0.0.1:{port}; DIRECT";
        }}
    }}

    // 3. 检查封锁域名后缀列表
    var suffixes = {suffixes_json};
    for (var i = 0; i < suffixes.length; i++) {{
        var s = suffixes[i];
        if (host === s || host.endsWith("." + s)) {{
            return "PROXY 127.0.0.1:{port}; DIRECT";
        }}
    }}

    // 其余所有流量直连出网，零转发开销，不影响内网与其他软件
    return "DIRECT";
}}
"""


def export_pac_file():
    """Write state/proxy.pac to disk."""
    try:
        os.makedirs(os.path.dirname(PAC_FILE), exist_ok=True)
        content = generate_pac_script(
            port=config.LISTEN_PORT,
            blocked_suffixes=config.BLOCKED_SUFFIXES,
            rewrites=config.SNI_REWRITE,
            passthrough_suffixes=config.PASSTHROUGH_SUFFIXES,
        )
        with open(PAC_FILE, "w", encoding="utf-8") as f:
            f.write(content)
        return PAC_FILE
    except Exception as e:
        log_warning(f"cannot write PAC file: {e}")
        return None


def ensure_rules_file():
    """Ensure rules.json exists with default configuration."""
    if not os.path.exists(RULES_FILE):
        data = dict(DEFAULT_RULES)
        data["updated_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
        try:
            with open(RULES_FILE, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2, ensure_ascii=False)
            log(f"  [OK] created default external rules file: {RULES_FILE}")
        except Exception as e:
            log_error(f"failed to create {RULES_FILE}: {e}")
    export_pac_file()


def load_rules(force=False):
    """Read rules.json and update runtime config."""
    with _lock:
        if not os.path.exists(RULES_FILE):
            ensure_rules_file()

        try:
            with open(RULES_FILE, "r", encoding="utf-8") as f:
                rules = json.load(f)
        except Exception as e:
            log_error(f"cannot read {RULES_FILE}: {e}, using defaults")
            rules = dict(DEFAULT_RULES)

        # Merge defaults if keys are missing
        for k, v in DEFAULT_RULES.items():
            if k not in rules:
                rules[k] = v

        # Apply to config attributes
        config.BLOCKED_SUFFIXES = [
            _normalize_suffix(s) for s in rules.get("blocked_suffixes", []) if s
        ]
        config.PASSTHROUGH_SUFFIXES = [
            _normalize_suffix(s) for s in rules.get("passthrough_suffixes", []) if s
        ]
        config.SNI_REWRITE = dict(rules.get("sni_rewrite", {}))
        config.ALLOWED_SNI_POOL = list(rules.get("allowed_sni_pool", []))
        config.PROXY_MODE = rules.get("proxy_mode", "pac")

        extra_wc = rules.get("extra_wildcard_bases", config.EXTRA_WILDCARD_BASES)
        config.EXTRA_WILDCARD_BASES = extra_wc
        config.WILDCARD_BASES = list(dict.fromkeys(
            [s.lower() for s in config.BLOCKED_SUFFIXES] + extra_wc
        ))

        export_pac_file()
        return rules


def save_rules(rules):
    """Save dictionary to rules.json atomically and reload config."""
    with _lock:
        rules["updated_at"] = time.strftime("%Y-%m-%d %H:%M:%S")
        tmp_file = RULES_FILE + ".tmp"
        try:
            with open(tmp_file, "w", encoding="utf-8") as f:
                json.dump(rules, f, indent=2, ensure_ascii=False)
            os.replace(tmp_file, RULES_FILE)
        except Exception as e:
            try:
                os.remove(tmp_file)
            except OSError:
                pass
            raise IOError(f"Failed to write {RULES_FILE}: {e}")

        # Update runtime
        config.BLOCKED_SUFFIXES = [
            _normalize_suffix(s) for s in rules.get("blocked_suffixes", []) if s
        ]
        config.PASSTHROUGH_SUFFIXES = [
            _normalize_suffix(s) for s in rules.get("passthrough_suffixes", []) if s
        ]
        config.SNI_REWRITE = dict(rules.get("sni_rewrite", {}))
        config.ALLOWED_SNI_POOL = list(rules.get("allowed_sni_pool", []))
        config.PROXY_MODE = rules.get("proxy_mode", "pac")
        extra_wc = rules.get("extra_wildcard_bases", config.EXTRA_WILDCARD_BASES)
        config.EXTRA_WILDCARD_BASES = extra_wc
        config.WILDCARD_BASES = list(dict.fromkeys(
            [s.lower() for s in config.BLOCKED_SUFFIXES] + extra_wc
        ))
        export_pac_file()
        log("  [OK] rules.json reloaded successfully")
        return True


def add_blocked_suffix(suffix):
    """Add a new suffix to blocked_suffixes in rules.json."""
    clean = _normalize_suffix(suffix)
    if not clean:
        return False
    rules = load_rules()
    suffixes = rules.get("blocked_suffixes", [])
    if clean not in suffixes:
        suffixes.append(clean)
        rules["blocked_suffixes"] = suffixes
        save_rules(rules)
        return True
    return False


def remove_blocked_suffix(suffix):
    """Remove a suffix from blocked_suffixes in rules.json."""
    clean = _normalize_suffix(suffix)
    rules = load_rules()
    suffixes = rules.get("blocked_suffixes", [])
    if clean in suffixes:
        suffixes.remove(clean)
        rules["blocked_suffixes"] = suffixes
        save_rules(rules)
        return True
    return False


def add_sni_rewrite(host, rewrite_sni):
    """Add or update an explicit SNI rewrite mapping."""
    h = host.strip().lower()
    r = rewrite_sni.strip().lower()
    if not h or not r:
        return False
    rules = load_rules()
    rewrites = rules.setdefault("sni_rewrite", {})
    rewrites[h] = r
    save_rules(rules)
    return True


def remove_sni_rewrite(host):
    """Remove an explicit SNI rewrite mapping."""
    h = host.strip().lower()
    rules = load_rules()
    rewrites = rules.get("sni_rewrite", {})
    if h in rewrites:
        del rewrites[h]
        save_rules(rules)
        return True
    return False


def set_proxy_mode(mode):
    """Set 'pac' or 'global' mode."""
    if mode not in ("pac", "global"):
        raise ValueError("Mode must be 'pac' or 'global'")
    rules = load_rules()
    rules["proxy_mode"] = mode
    save_rules(rules)
    return True


def get_strategy_cache():
    """Read the contents of strategies.json."""
    if not os.path.exists(config.STRATEGY_FILE):
        return {}
    try:
        with open(config.STRATEGY_FILE, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception as e:
        log_warning(f"cannot read {config.STRATEGY_FILE}: {e}")
        return {}


def delete_strategy_cache_entry(domain):
    """Remove a domain from strategies.json and in-memory cache."""
    d = domain.strip().lower()
    cache = get_strategy_cache()
    if d in cache:
        del cache[d]
        try:
            with open(config.STRATEGY_FILE, "w", encoding="utf-8") as f:
                json.dump(cache, f, indent=2, ensure_ascii=False)
        except Exception as e:
            log_error(f"cannot update {config.STRATEGY_FILE}: {e}")
            return False

        # update in-memory upstream cache if loaded
        try:
            from . import upstream
            with upstream._strategy_lock:
                upstream._strategy_cache.pop(d, None)
        except Exception:
            pass
        return True
    return False


def clear_strategy_cache():
    """Clear all entries in strategies.json and in-memory cache."""
    try:
        with open(config.STRATEGY_FILE, "w", encoding="utf-8") as f:
            json.dump({}, f, indent=2)
    except Exception as e:
        log_error(f"cannot clear {config.STRATEGY_FILE}: {e}")
        return False

    try:
        from . import upstream
        with upstream._strategy_lock:
            upstream._strategy_cache.clear()
    except Exception:
        pass
    return True
